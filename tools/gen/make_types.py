#!/usr/bin/env python3
"""make_types.py - the ported object files -> <out>/types_gen.c: includes every one and builds
the table of object types from their TYPEDEF(NAME) lines (game/hur.h).
    python3 tools/gen/make_types.py <out>/types_gen.c <game folder> <folder> [more folders]
Each folder is searched with its subfolders; paths are written relative to the game folder."""
import os, re, sys

out, root, dirs = sys.argv[1], sys.argv[2], sys.argv[3:]
paths = []
for d in dirs:
    for wroot, _, fs in os.walk(d):
        paths += [os.path.join(wroot, f) for f in fs if f.endswith(".c")]
paths = sorted(set(paths))
names = []
lines = ["/* generated by tools/gen/make_types.py: the ported objects */"]
for f in paths:
    rel = os.path.relpath(f, root)
    lines.append('#include "%s"' % rel.replace(os.sep, "/"))
    for m in re.finditer(r"^TYPEDEF\((\w+)\)", open(f).read(), re.M):
        if m.group(1) in names:
            sys.exit("*** make_types: %s defined twice (%s)" % (m.group(1), f))
        names.append(m.group(1))
lines.append("static const TypeDef *const gegner_types[200] = {")
for n in names:
    lines.append("\t[%s] = &typedef_%s," % (n, n))
lines.append("};")
new = "\n".join(lines) + "\n"
os.makedirs(os.path.dirname(out) or ".", exist_ok=True)
if not os.path.exists(out) or open(out).read() != new:
    open(out, "w").write(new)
print("  %d object types from %d files" % (len(names), len(paths)))
