#!/usr/bin/env python3
"""make_hur_tables.py - C tables from Hurrican's source (run once by hand; the results are in
game/): game/hur_enums.h (object, action, projectile, particle, sound, music numbers, as
Hurrican's headers have them) and game/hur_tables.h (each object type's picture and frame layout
- Gegner_Helper.cpp sprites[] - and collision rectangle - GegnerClass.cpp GegnerRect).
    python3 tools/gen/make_hur_tables.py <Hurrican/src> game/"""
import os, re, sys

src, out = sys.argv[1], sys.argv[2]
rd = lambda p: open(os.path.join(src, p), encoding="latin-1").read()


def enum_block(text, start_pat, prefix=""):
    i = text.index(start_pat)
    j = text.index("};", i)
    body = re.sub(r"//.*", "", text[i:j])
    vals, cur = [], -1
    for m in re.finditer(r"\b([A-Z_][A-Z0-9_]*)\s*(?:=\s*([0-9]+))?\s*,?", body[body.index("{") + 1:]):
        name, v = m.group(1), m.group(2)
        cur = int(v) if v is not None else cur + 1
        vals.append((prefix + name, cur))
    return vals


stuff = rd("enemies/Gegner_Stuff.hpp")
gegner = enum_block(stuff, "enum Enemy")
actions = enum_block(stuff, "enum EnemyAction", "GEGNER_")
boss_actions = enum_block(stuff[stuff.index("// Zwischenbosse"):], "enum {", "GEGNER_")
proj = enum_block(rd("Projectiles.hpp"), "enum {")
part_text = rd("Partikelsystem.hpp")
parts = []
pos = 0
while True:
    k = part_text.find("enum {", pos)
    if k < 0:
        break
    parts += enum_block(part_text[k:], "enum {")
    pos = k + 6
snd_text = rd("DX8Sound.hpp")
k = snd_text.index("enum {")
sounds = enum_block(snd_text[k:], "enum {", "SOUND_")
k2 = snd_text.index("enum {", k + 6)
music = enum_block(snd_text[k2:], "enum {", "MUSIC_")
pl = rd("Player.hpp")
pa = enum_block(pl, "enum class PlayerActionEnum", "PA_")

names = {}
lines = ["/* Hurrican's numbers (generated by tools/gen/make_hur_tables.py from Hurrican's source) */",
         "#ifndef HUR_ENUMS_H", "#define HUR_ENUMS_H"]
for title, vals in (("objects (Gegner_Stuff.hpp)", gegner), ("enemy actions (GEGNER::)", actions + boss_actions),
                    ("projectiles (Projectiles.hpp)", proj), ("particles (Partikelsystem.hpp)", parts),
                    ("sounds (SOUND::)", sounds), ("music (MUSIC::)", music), ("player actions", pa)):
    lines.append("/* %s */" % title)
    lines.append("enum {")
    for n, v in vals:
        if n in names:
            if names[n] != v:
                print("conflict", n, names[n], v)
            continue
        names[n] = v
        lines.append("\t%s = %d," % (n, v))
    lines.append("};")
lines.append("#endif")
open(os.path.join(out, "hur_enums.h"), "w").write("\n".join(lines) + "\n")

# pictures: Gegner_Helper.cpp sprites[] (index = object number), plus the four loaded at start
gh = rd("Gegner_Helper.cpp")
body = gh[gh.index("SpriteData sprites[] = {"):]
body = body[:body.index("};")]
pics = []
for m in re.finditer(r"\{\s*(nullptr|\"([^\"]+)\")\s*,\s*(\d+),\s*(\d+),\s*(\d+),\s*(\d+),\s*(\d+),\s*(\d+)\s*\}", body):
    pics.append((m.group(2), [int(m.group(i)) for i in range(3, 9)]))
gc = rd("GegnerClass.cpp")
fixed = {}
for m in re.finditer(r"pGegnerGrafix\[(\w+)\]->LoadImage\(\"([^\"]+)\",\s*(\d+),\s*(\d+),\s*(\d+),\s*(\d+),\s*(\d+),\s*(\d+)\)", gc):
    fixed[m.group(1)] = (m.group(2), [int(m.group(i)) for i in range(3, 9)])
ids = dict(gegner)
rects = {}
for m in re.finditer(r"GegnerRect\[(\w+)\]\.(left|right|top|bottom)\s*=\s*([-0-9+*/ ()]+);", gc):
    rects.setdefault(m.group(1), {})[m.group(2)] = int(eval(m.group(3)))
N = 200
t = ["/* each object type's picture and collision rectangle (generated by tools/gen/make_hur_tables.py) */",
     "#ifndef HUR_TABLES_H", "#define HUR_TABLES_H",
     "static const char *const gegner_pic_name[%d] = {" % N]
pn = [None] * N
for i, (fn, _) in enumerate(pics):
    if i < N:
        pn[i] = fn
for k, (fn, _) in fixed.items():
    if k in ids:
        pn[ids[k]] = fn
for i in range(N):
    t.append("\t%s," % ('"%s"' % pn[i] if pn[i] else "0"))
t.append("};")
t.append("/* GegnerRect: left, top, right, bottom */")
t.append("static const int16_t gegner_rect_init[%d][4] = {" % N)
byid = {ids[k]: v for k, v in rects.items() if k in ids}
for i in range(N):
    r = byid.get(i, {})
    t.append("\t{ %d, %d, %d, %d }," % (r.get("left", 0), r.get("top", 0), r.get("right", 0), r.get("bottom", 0)))
t.append("};")
t.append("#endif")
open(os.path.join(out, "hur_tables.h"), "w").write("\n".join(t) + "\n")
print("objects %d, projectiles %d, particles %d, sounds %d, pictures %d, rects %d" %
      (len(gegner), len(proj), len(parts), len(sounds), sum(1 for x in pn if x), len(byid)))
